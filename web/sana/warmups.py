def before_html(title, items):
    return ('<div class="wublock"><div class="wuhead">🔥 %s</div><ol class="wu">%s</ol>'
            '<p class="minisub"><b>بعد الإحماء:</b> ارتح دقيقة، ثم ابدأ الجلسة.</p></div>') % (title, '\n'.join(items))


def after_html(title, items, mob_title, mob_items, tail=''):
    h = '<div class="wublock after"><div class="wuhead">🧘 %s</div><ol class="wu">%s</ol>' % (title, '\n'.join(items))
    h += '<div class="wuhead mob">🤸 %s</div><ol class="wu">%s</ol>' % (mob_title, '\n'.join(mob_items))
    if tail:
        h += '<p class="note">%s</p>' % tail
    return h + '</div>'


