def it(ar, en, dose, how):
    return ('<li><b>%s</b> <span class="en">%s</span> — <b class="dose">%s</b><br>'
            '<span class="how">%s</span></li>') % (ar, en, dose, how)


REC = {}


def block(title, cls, before_title, before, after_title, after, extra=''):
    REC[cls] = (before_title, before, after_title, after, extra)
    h = ['<div class="wublock">']
    h.append('<div class="wuband %s">%s</div>' % (cls, title))
    h.append('<h3>%s</h3><ol class="wu">' % before_title)
    h += before
    h.append('</ol>')
    h.append('<h3>%s</h3><ol class="wu">' % after_title)
    h += after
    h.append('</ol>')
    if extra:
        h.append('<p class="note">%s</p>' % extra)
    h.append('</div>')
    return '\n'.join(h)


