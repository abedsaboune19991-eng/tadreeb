def d10_rules(table):
    names = {1: 'المرحلة الأولى', 2: 'المرحلة الثانية', 3: 'المرحلة الثالثة', 4: 'المرحلة الرابعة'}
    h = '<h3>الدقائق العشر اليومية</h3><p>' + D10_RULE + '</p><ul class="plain">'
    for k, items in table.items():
        import re
        names_ = [re.sub(r'<[^>]+>', '', re.match(r'<li><b>(.*?)</b>', x).group(1)) for x in items]
        h += '<li><b>%s:</b> %s.</li>' % (names[k], '، ثم '.join(names_))
    return h + '</ul>'
