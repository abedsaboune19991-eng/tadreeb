    for i, (t, e, items) in enumerate(B['tests'], 1):
        h.append('<div class="ex"><h4><span class="no">%d</span> %s <span class="dash">—</span> <span class="en">%s</span></h4><ul class="plain">%s</ul></div>' % (i, t, e, ''.join('<li>%s</li>' % x for x in items)))
    h.append('<div class="measure"><b>قبل المرحلة التالية:</b> قارن أرقامك بشرط الدخول وعلامة النجاح. وإن نجحت في أغلبها فانتقل، وإلا فكرّر الأسابيع 9 إلى 11 من هذه المرحلة ثم اختبر مرة أخرى. وخذ بعد الاختبارات 3 إلى 4 أيام خفيفة.</div></section>')
    out.append('\n'.join(h))
    return '\n'.join(out)


