    out.append(session('run', 'اليوم الثاني', 'الجري والسرعة', 'Running &amp; Speed', 'المدة 60 إلى 75 دقيقة', body))
    # اليوم الثالث
    out.append(session('push', 'اليوم الثالث', 'الدفع والترايسبس والأوتار العلوية', 'Push, Triceps &amp; Upper Tendons', 'المدة نحو 70 دقيقة', mt_box('push', 'الأسبوعان الرابع والثامن') + ORDER_NOTE + yexlist(B['push'])))
    # اليوم الرابع
    body = ('<p class="note"><b>البليومترك:</b> على أرض أنعم إن وجدت (عشب أو تراب)، وبحذاء جيد. وعدّ ملامسات القدم للأرض: '
            'لا تتجاوز ما هو مكتوب. وإن ظهر ألم في أخيل أو الركبة فاحذف القفز ذلك الأسبوع وأبقِ تمارين الأوتار.</p>' + ORDER_NOTE + yexlist(B['legs'])
            + blockbox('جلسة السحب المصغرة', 'تدعم اليوم الأول. بعد آخر تمرين وراحة 3 دقائق، 10 إلى 12 دقيقة.', B['mini_pull']))
    out.append(session('legs', 'اليوم الرابع', 'الأرجل والبليومترك والأوتار السفلية', 'Legs, Plyometrics &amp; Lower Tendons', 'المدة نحو 80 دقيقة', body))
    # اليوم الخامس
    steps = ''.join(run_week('الأسبوع %s%s' % (WEEKS_AR[w - 1], ' (تخفيف)' if w in (4, 8) else ''), d5_steps(bi + 1, w)) for w in range(1, 12))
    body = steps + blockbox('الجلسة المتوسطة لكل الجسم', 'بعد الجري وراحة 10 دقائق، 25 إلى 30 دقيقة. وإن طال اليوم فاجعل الجري صباحًا والجلسة مساءً.', B['full'])
