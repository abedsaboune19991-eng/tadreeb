    # الأسبوع 12
    h = ['<section class="session"><div class="dayband test"><div class="dn">الأسبوع 12</div><div class="dt">اختبارات المرحلة %s <span class="en">Testing Week</span></div><div class="dur">5 جلسات خفيفة الحجم</div></div>' % B['num']]
