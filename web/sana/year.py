def wrap(cls, body):
    wt, wl = WARM[cls]
    head = before_html('قبل التمرين — ' + wt, wl)
    if cls == 'long':
        tail = after_html('بعد الجلسة المتوسطة — التهدئة', [W.WALK2],
                          'ثم الليونة: الروتين الأسبوعي (25 دقيقة) — الروتين اليومي كاملًا، ثم ليونة المهارات',
                          W.MOB_DAILY + W.MOB_WEEKLY_EXTRA + SKILL_MOB, W.TAILS['long'])
    else:
        ct, cl = COOL[cls]
        tail = after_html('بعد التمرين — ' + ct, cl, 'ثم الليونة: الروتين اليومي (10 دقائق)', W.MOB_DAILY, TAIL[cls])
    return head + body + tail


def session(cls, daynum, tar, ten, dur, body):
    return '<section class="session">%s%s</section>' % (day_band(cls, daynum, tar, ten, dur), wrap(cls, body))


def blockbox(title, sub, exs):
    return ('<div class="mini"><div class="minih">➕ %s</div><p class="minisub">%s</p>'
            '<p class="minisub"><b>القاعدة:</b> جهد متوسط، بلا فشل. وفي ليلة النوم القليل احذف هذه الجلسة.</p>%s</div>') % (title, sub, yexlist(exs))


