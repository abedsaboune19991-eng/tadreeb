def d2_steps(block, w):
    """خطوات اليوم الثاني لأسبوع w (1–11)"""
    warm = 'إحماء: 10 دقائق جري هادئ (أخضر)، ثم ' + ('4 انطلاقات × 100 متر.' if block != 3 else '4 تسارعات × 30 مترًا بنحو 80٪.')
    cool = 'تهدئة: 5 دقائق مشي.'
    if w in (4, 8):
        return [warm, '4 جولات: 400 متر بوتيرة الفترات (برتقالي)، ثم راحة 90 ثانية مشيًا.', DRILLS, cool]
    sub = 0 if w <= 3 else (1 if w <= 7 else 2)
    k = (w - 1) % 4  # 0,1,2 داخل المرحلة الفرعية
    if block == 1:
        main = [
            ['%d جولات: 400 متر بوتيرة الفترات (برتقالي، T − 35 ثانية)، ثم راحة 90 ثانية مشيًا.' % (6 + k)],
            ['%d جولات: 800 متر بوتيرة الفترات (برتقالي)، ثم راحة دقيقتين مشيًا.' % (4 + min(k, 1))],
            ['%d جولات: 1000 متر بوتيرة بين الثابت والسريع (T − 20 ثانية)، ثم راحة دقيقتين مشيًا.' % (3 + min(k, 1))],
        ][sub]
        extra = ['سرعة قصوى (Sprints): 4 جولات × 60 مترًا، ثم راحة 90 ثانية مشيًا.']
    elif block == 2:
        main = [
            ['%d جولات: 200 متر سريعة (T − 45 ثانية)، ثم راحة 90 ثانية مشيًا.' % (8 + k)],
            ['جري ثابت (أصفر، T) لمدة %d دقيقة متواصلة.' % (15 + 3 * k)],
            ['%d جولات: 1000 متر بوتيرة T − 25 ثانية، ثم راحة دقيقتين مشيًا.' % (4 + min(k, 1))],
        ][sub]
        extra = ['صعود مرتفع (Hill Sprints): 6 جولات × 10 ثوانٍ بأقصى قوة على أي منحدر، والعودة مشيًا هي الراحة.']
    elif block == 3:
        main = [
            ['سرعة قصوى من الوقوف: %d جولات × 40 مترًا، ثم راحة دقيقتين مشيًا.' % (6 + k),
             '3 جولات: 200 متر سريعة، ثم راحة دقيقتين.'],
            ['سرعة قصوى: %d جولات × 60 مترًا، ثم راحة دقيقتين ونصف.' % (6 + k),
             'صعود مرتفع: 6 جولات × 10 ثوانٍ، والعودة مشيًا هي الراحة.'],
            ['سرعة طائرة (Flying Sprints): %d جولات: 30 مترًا تسارع ثم 30 مترًا بأقصى سرعة، ثم راحة 3 دقائق.' % (5 + min(k, 1)),
             '3 جولات: 400 متر بوتيرة الفترات، ثم راحة دقيقتين.'],
        ][sub]
        extra = []
    else:
        main = [
            ['%d جولات: 1200 متر بوتيرة T − 15 ثانية، ثم راحة دقيقتين مشيًا.' % (3 + min(k, 1))],
            ['%d جولات: 800 متر بوتيرة T − 30 ثانية، ثم راحة 90 ثانية مشيًا.' % (5 + min(k, 1))],
            ['3 جولات: 1000 متر بالوتيرة التي تريدها في اختبار 5 كم، ثم راحة دقيقتين مشيًا.'] if w < 11
            else ['4 جولات: 400 متر بوتيرة سريعة مريحة، ثم راحة 90 ثانية (تخفيف قبل الاختبار).'],
        ][sub]
        extra = ['سرعة قصوى: 4 جولات × 60 مترًا، ثم راحة دقيقتين.'] if w < 11 else []
    return [warm] + main + extra + [DRILLS, cool]


def d5_steps(block, w):
    """خطوات الجري الطويل لأسبوع w"""
    if block == 1:
        mins = {1: 50, 2: 55, 3: 60, 4: 45, 5: 60, 6: 65, 7: 70, 8: 50, 9: 70, 10: 70, 11: 75}[w]
        tail = 'جري هادئ %d دقيقة (أخضر، T + 60 إلى 90 ثانية).' % mins
    elif block == 2:
        mins = {1: 55, 2: 60, 3: 65, 4: 45, 5: 60, 6: 65, 7: 70, 8: 50, 9: 70, 10: 75, 11: 75}[w]
        tail = 'جري %d دقيقة: كله هادئ (أخضر)، وآخر %d دقائق ثابتة (أصفر).' % (mins, 0 if w in (4, 8) else 10)
        if w in (4, 8):
            tail = 'جري هادئ %d دقيقة (أخضر).' % mins
    elif block == 3:
        mins = {1: 45, 2: 50, 3: 50, 4: 40, 5: 50, 6: 55, 7: 55, 8: 40, 9: 55, 10: 55, 11: 50}[w]
        tail = 'جري هادئ %d دقيقة (أخضر). هذه المرحلة للانفجار، فالجري الطويل أقصر عمدًا.' % mins
    else:
        mins = {1: 60, 2: 65, 3: 70, 4: 50, 5: 70, 6: 75, 7: 80, 8: 55, 9: 75, 10: 70, 11: 40}[w]
        tail = ('جري %d دقيقة: هادئ (أخضر)، وآخر 15 دقيقة ثابتة (أصفر).' % mins) if w not in (4, 8, 11) else ('جري هادئ %d دقيقة (أخضر).' % mins)
    return [tail, '%d انطلاقات × 100 متر في الساحة، والعودة مشيًا.' % (4 if w in (4, 8, 11) else 6)]


